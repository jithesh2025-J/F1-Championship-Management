-- ---------------------------------------------------------------------------
-- COUNTRY
-- ---------------------------------------------------------------------------
CREATE TABLE country (
  country_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  country_code   VARCHAR2(8),
  country_name   VARCHAR2(100) NOT NULL,
  CONSTRAINT pk_country PRIMARY KEY (country_id),
  CONSTRAINT uq_country_name UNIQUE (country_name),
  CONSTRAINT uq_country_code UNIQUE (country_code)
);

-- ---------------------------------------------------------------------------
-- SEASON
-- ---------------------------------------------------------------------------
CREATE TABLE season (
  season_year    NUMBER(4) NOT NULL,
  season_name    VARCHAR2(80),
  start_date     DATE,
  end_date       DATE,
  notes          VARCHAR2(400),
  CONSTRAINT pk_season PRIMARY KEY (season_year),
  CONSTRAINT ck_season_year CHECK (season_year BETWEEN 1950 AND 2100),
  CONSTRAINT ck_season_dates CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

-- ---------------------------------------------------------------------------
-- TEAM (constructors)
-- constructor_ref is the Jolpica/Ergast constructorId (natural key).
-- ---------------------------------------------------------------------------
CREATE TABLE team (
  team_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  constructor_ref  VARCHAR2(50) NOT NULL,
  team_name        VARCHAR2(120) NOT NULL,
  nationality      VARCHAR2(80),
  country_id       NUMBER,
  wikipedia_url    VARCHAR2(400),
  primary_color    VARCHAR2(20),
  notes            VARCHAR2(400),
  source_system    VARCHAR2(30) DEFAULT 'JOLPICA' NOT NULL,
  CONSTRAINT pk_team PRIMARY KEY (team_id),
  CONSTRAINT uq_team_ref UNIQUE (constructor_ref),
  CONSTRAINT uq_team_name UNIQUE (team_name),
  CONSTRAINT fk_team_country FOREIGN KEY (country_id) REFERENCES country (country_id),
  CONSTRAINT ck_team_source CHECK (source_system IN ('JOLPICA', 'MANUAL', 'ILLUSTRATIVE'))
);

CREATE INDEX ix_team_country ON team (country_id);

-- ---------------------------------------------------------------------------
-- DRIVER
-- driver_ref is the Jolpica/Ergast driverId (natural key).
-- Nationality is stored as reported by the source; country_id is a derived lookup.
-- ---------------------------------------------------------------------------
CREATE TABLE driver (
  driver_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  driver_ref         VARCHAR2(50) NOT NULL,
  driver_code        VARCHAR2(5),
  permanent_number   NUMBER(3),
  first_name         VARCHAR2(80) NOT NULL,
  last_name          VARCHAR2(80) NOT NULL,
  date_of_birth      DATE,
  nationality        VARCHAR2(80),
  country_id         NUMBER,
  wikipedia_url      VARCHAR2(400),
  notes              VARCHAR2(400),
  source_system      VARCHAR2(30) DEFAULT 'JOLPICA' NOT NULL,
  CONSTRAINT pk_driver PRIMARY KEY (driver_id),
  CONSTRAINT uq_driver_ref UNIQUE (driver_ref),
  CONSTRAINT fk_driver_country FOREIGN KEY (country_id) REFERENCES country (country_id),
  CONSTRAINT ck_driver_number CHECK (permanent_number IS NULL OR permanent_number BETWEEN 1 AND 99),
  CONSTRAINT ck_driver_source CHECK (source_system IN ('JOLPICA', 'MANUAL', 'ILLUSTRATIVE'))
);

CREATE INDEX ix_driver_name ON driver (last_name, first_name);
CREATE INDEX ix_driver_country ON driver (country_id);

-- ---------------------------------------------------------------------------
-- DRIVER_CONTRACT
-- Season-specific (and mid-season) driver–team assignment.
-- A driver may have more than one team in one season (transfers / substitutes).
-- ---------------------------------------------------------------------------
CREATE TABLE driver_contract (
  contract_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  driver_id      NUMBER NOT NULL,
  team_id        NUMBER NOT NULL,
  season_year    NUMBER(4) NOT NULL,
  car_number     NUMBER(3),
  role_note      VARCHAR2(80),
  CONSTRAINT pk_driver_contract PRIMARY KEY (contract_id),
  CONSTRAINT uq_driver_team_season UNIQUE (driver_id, team_id, season_year),
  CONSTRAINT fk_dc_driver FOREIGN KEY (driver_id) REFERENCES driver (driver_id),
  CONSTRAINT fk_dc_team FOREIGN KEY (team_id) REFERENCES team (team_id),
  CONSTRAINT fk_dc_season FOREIGN KEY (season_year) REFERENCES season (season_year),
  CONSTRAINT ck_dc_car_number CHECK (car_number IS NULL OR car_number BETWEEN 1 AND 99)
);

CREATE INDEX ix_dc_season ON driver_contract (season_year);
CREATE INDEX ix_dc_team ON driver_contract (team_id);

-- ---------------------------------------------------------------------------
-- CIRCUIT
-- ---------------------------------------------------------------------------
CREATE TABLE circuit (
  circuit_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  circuit_ref    VARCHAR2(50) NOT NULL,
  circuit_name   VARCHAR2(150) NOT NULL,
  locality       VARCHAR2(100),
  country_id     NUMBER,
  latitude       NUMBER(10, 6),
  longitude      NUMBER(10, 6),
  wikipedia_url  VARCHAR2(400),
  CONSTRAINT pk_circuit PRIMARY KEY (circuit_id),
  CONSTRAINT uq_circuit_ref UNIQUE (circuit_ref),
  CONSTRAINT fk_circuit_country FOREIGN KEY (country_id) REFERENCES country (country_id)
);

CREATE INDEX ix_circuit_country ON circuit (country_id);

-- ---------------------------------------------------------------------------
-- RACE  (Grand Prix weekend — one row per round)
-- Sprint sessions are NOT separate races; they are result rows with SESSION_TYPE.
-- ---------------------------------------------------------------------------
CREATE TABLE race (
  race_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  season_year     NUMBER(4) NOT NULL,
  round_number    NUMBER(2) NOT NULL,
  circuit_id      NUMBER NOT NULL,
  race_name       VARCHAR2(150) NOT NULL,
  race_date       DATE,
  race_time_utc   VARCHAR2(20),
  wikipedia_url   VARCHAR2(400),
  has_sprint      CHAR(1) DEFAULT 'N' NOT NULL,
  source_system   VARCHAR2(30) DEFAULT 'JOLPICA' NOT NULL,
  CONSTRAINT pk_race PRIMARY KEY (race_id),
  CONSTRAINT uq_race_season_round UNIQUE (season_year, round_number),
  CONSTRAINT fk_race_season FOREIGN KEY (season_year) REFERENCES season (season_year),
  CONSTRAINT fk_race_circuit FOREIGN KEY (circuit_id) REFERENCES circuit (circuit_id),
  CONSTRAINT ck_race_round CHECK (round_number BETWEEN 1 AND 30),
  CONSTRAINT ck_race_sprint CHECK (has_sprint IN ('Y', 'N')),
  CONSTRAINT ck_race_source CHECK (source_system IN ('JOLPICA', 'MANUAL', 'ILLUSTRATIVE'))
);

CREATE INDEX ix_race_circuit ON race (circuit_id);
CREATE INDEX ix_race_date ON race (race_date);

-- ---------------------------------------------------------------------------
-- QUALIFYING_RESULT
-- session_type: QUALIFYING (GP) or SPRINT_QUALIFYING
-- ---------------------------------------------------------------------------
CREATE TABLE qualifying_result (
  quali_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  race_id         NUMBER NOT NULL,
  driver_id       NUMBER NOT NULL,
  team_id         NUMBER NOT NULL,
  session_type    VARCHAR2(20) DEFAULT 'QUALIFYING' NOT NULL,
  position        NUMBER(2),
  q1_time         VARCHAR2(20),
  q2_time         VARCHAR2(20),
  q3_time         VARCHAR2(20),
  source_system   VARCHAR2(30) DEFAULT 'JOLPICA' NOT NULL,
  is_verified     CHAR(1) DEFAULT 'Y' NOT NULL,
  CONSTRAINT pk_qualifying_result PRIMARY KEY (quali_id),
  CONSTRAINT uq_quali_driver_session UNIQUE (race_id, driver_id, session_type),
  CONSTRAINT fk_quali_race FOREIGN KEY (race_id) REFERENCES race (race_id),
  CONSTRAINT fk_quali_driver FOREIGN KEY (driver_id) REFERENCES driver (driver_id),
  CONSTRAINT fk_quali_team FOREIGN KEY (team_id) REFERENCES team (team_id),
  CONSTRAINT ck_quali_session CHECK (session_type IN ('QUALIFYING', 'SPRINT_QUALIFYING')),
  CONSTRAINT ck_quali_pos CHECK (position IS NULL OR position BETWEEN 1 AND 30),
  CONSTRAINT ck_quali_verified CHECK (is_verified IN ('Y', 'N')),
  CONSTRAINT ck_quali_source CHECK (source_system IN ('JOLPICA', 'MANUAL', 'ILLUSTRATIVE'))
);

CREATE INDEX ix_quali_driver ON qualifying_result (driver_id);
CREATE INDEX ix_quali_team ON qualifying_result (team_id);

-- ---------------------------------------------------------------------------
-- RACE_RESULT
-- session_type RACE = Grand Prix; SPRINT = sprint race.
-- points come from the source for that session. Championship views SUM both.
-- GP-only statistics must filter session_type = 'RACE'.
-- ---------------------------------------------------------------------------
CREATE TABLE race_result (
  result_id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  race_id                NUMBER NOT NULL,
  driver_id              NUMBER NOT NULL,
  team_id                NUMBER NOT NULL,
  session_type           VARCHAR2(20) DEFAULT 'RACE' NOT NULL,
  grid_position          NUMBER(2),
  finish_position        NUMBER(2),
  position_text          VARCHAR2(8),
  classification_status  VARCHAR2(80) NOT NULL,
  points                 NUMBER(6, 2) DEFAULT 0 NOT NULL,
  laps_completed         NUMBER(3),
  time_text              VARCHAR2(40),
  milliseconds           NUMBER(12),
  fastest_lap            NUMBER(3),
  fastest_lap_time       VARCHAR2(20),
  fastest_lap_rank       NUMBER(2),
  source_system          VARCHAR2(30) DEFAULT 'JOLPICA' NOT NULL,
  is_verified            CHAR(1) DEFAULT 'Y' NOT NULL,
  source_url             VARCHAR2(400),
  CONSTRAINT pk_race_result PRIMARY KEY (result_id),
  CONSTRAINT uq_result_driver_session UNIQUE (race_id, driver_id, session_type),
  CONSTRAINT fk_rr_race FOREIGN KEY (race_id) REFERENCES race (race_id),
  CONSTRAINT fk_rr_driver FOREIGN KEY (driver_id) REFERENCES driver (driver_id),
  CONSTRAINT fk_rr_team FOREIGN KEY (team_id) REFERENCES team (team_id),
  CONSTRAINT ck_rr_session CHECK (session_type IN ('RACE', 'SPRINT')),
  CONSTRAINT ck_rr_grid CHECK (grid_position IS NULL OR grid_position BETWEEN 0 AND 30),
  CONSTRAINT ck_rr_finish CHECK (finish_position IS NULL OR finish_position BETWEEN 1 AND 30),
  CONSTRAINT ck_rr_points CHECK (points >= 0),
  CONSTRAINT ck_rr_verified CHECK (is_verified IN ('Y', 'N')),
  CONSTRAINT ck_rr_source CHECK (source_system IN ('JOLPICA', 'MANUAL', 'ILLUSTRATIVE'))
);

CREATE INDEX ix_rr_driver ON race_result (driver_id);
CREATE INDEX ix_rr_team ON race_result (team_id);
CREATE INDEX ix_rr_session ON race_result (session_type);
CREATE INDEX ix_rr_points ON race_result (race_id, points);

COMMENT ON TABLE race_result IS 'Session results. SESSION_TYPE distinguishes GP and sprint. Points are source-awarded per session, not a hardcoded scoring table.';
COMMENT ON COLUMN race_result.points IS 'Points awarded by the official session result (includes sprint points when session_type=SPRINT).';

-- ---------------------------------------------------------------------------
-- PIT_STOP
-- ---------------------------------------------------------------------------
CREATE TABLE pit_stop (
  pit_stop_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  race_id        NUMBER NOT NULL,
  driver_id      NUMBER NOT NULL,
  stop_number    NUMBER(2) NOT NULL,
  lap_number     NUMBER(3),
  stop_time      VARCHAR2(20),
  duration_text  VARCHAR2(20),
  duration_ms    NUMBER(10),
  source_system  VARCHAR2(30) DEFAULT 'JOLPICA' NOT NULL,
  CONSTRAINT pk_pit_stop PRIMARY KEY (pit_stop_id),
  CONSTRAINT uq_pit_stop UNIQUE (race_id, driver_id, stop_number),
  CONSTRAINT fk_ps_race FOREIGN KEY (race_id) REFERENCES race (race_id),
  CONSTRAINT fk_ps_driver FOREIGN KEY (driver_id) REFERENCES driver (driver_id),
  CONSTRAINT ck_ps_stop CHECK (stop_number BETWEEN 1 AND 20),
  CONSTRAINT ck_ps_source CHECK (source_system IN ('JOLPICA', 'MANUAL', 'ILLUSTRATIVE'))
);

CREATE INDEX ix_ps_driver ON pit_stop (driver_id);

-- ---------------------------------------------------------------------------
-- PENALTY
-- Historical penalties are sparsely published in Ergast/Jolpica.
-- This table supports management CRUD and optional imported DSQ notes.
-- Rows with is_illustrative='Y' must never feed championship totals.
-- ---------------------------------------------------------------------------
CREATE TABLE penalty (
  penalty_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  race_id          NUMBER,
  driver_id        NUMBER,
  team_id          NUMBER,
  penalty_type     VARCHAR2(80) NOT NULL,
  description      VARCHAR2(400),
  points_penalty   NUMBER(4, 1) DEFAULT 0,
  is_illustrative  CHAR(1) DEFAULT 'N' NOT NULL,
  created_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_penalty PRIMARY KEY (penalty_id),
  CONSTRAINT fk_pen_race FOREIGN KEY (race_id) REFERENCES race (race_id),
  CONSTRAINT fk_pen_driver FOREIGN KEY (driver_id) REFERENCES driver (driver_id),
  CONSTRAINT fk_pen_team FOREIGN KEY (team_id) REFERENCES team (team_id),
  CONSTRAINT ck_pen_points CHECK (points_penalty >= 0),
  CONSTRAINT ck_pen_illust CHECK (is_illustrative IN ('Y', 'N'))
);

CREATE INDEX ix_pen_race ON penalty (race_id);
CREATE INDEX ix_pen_driver ON penalty (driver_id);

-- ---------------------------------------------------------------------------
-- SPONSOR + TEAM_SPONSOR (many-to-many, season-scoped)
-- Management data. Not historical F1 commercial contracts.
-- ---------------------------------------------------------------------------
CREATE TABLE sponsor (
  sponsor_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  sponsor_name   VARCHAR2(120) NOT NULL,
  industry       VARCHAR2(80),
  country_id     NUMBER,
  website_url    VARCHAR2(400),
  is_illustrative CHAR(1) DEFAULT 'Y' NOT NULL,
  notes          VARCHAR2(400),
  created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at     TIMESTAMP,
  CONSTRAINT pk_sponsor PRIMARY KEY (sponsor_id),
  CONSTRAINT uq_sponsor_name UNIQUE (sponsor_name),
  CONSTRAINT fk_sponsor_country FOREIGN KEY (country_id) REFERENCES country (country_id),
  CONSTRAINT ck_sponsor_illust CHECK (is_illustrative IN ('Y', 'N'))
);

CREATE TABLE team_sponsor (
  team_id        NUMBER NOT NULL,
  sponsor_id     NUMBER NOT NULL,
  season_year    NUMBER(4) NOT NULL,
  deal_note      VARCHAR2(200),
  is_illustrative CHAR(1) DEFAULT 'Y' NOT NULL,
  CONSTRAINT pk_team_sponsor PRIMARY KEY (team_id, sponsor_id, season_year),
  CONSTRAINT fk_ts_team FOREIGN KEY (team_id) REFERENCES team (team_id),
  CONSTRAINT fk_ts_sponsor FOREIGN KEY (sponsor_id) REFERENCES sponsor (sponsor_id),
  CONSTRAINT fk_ts_season FOREIGN KEY (season_year) REFERENCES season (season_year),
  CONSTRAINT ck_ts_illust CHECK (is_illustrative IN ('Y', 'N'))
);

CREATE INDEX ix_ts_sponsor ON team_sponsor (sponsor_id);
